#!/usr/bin/env python3
"""Lay out the big data (samples, music streams, movies) in ROM above the code for the Sega mapper.

usage: mkbanks.py BUILD_DIR    (reads BUILD_DIR/banked_*.txt: lines "<window>[:<group>] <symbol> <file>";
                                the items of a group are placed one after the other, read through
                                one mapping: they share the <symbol>_page)

The first 1 MB (pages 0-1) is always mapped; the code and graphics use its first CODE_END bytes.
Every banked item is placed at some ROM offset and is read through a window:
  S  samples        -> its page mapped at 0x180000 by writing it to 0xA130F7 (512 KB window)
  M  music streams  -> its page and the next mapped at 0x200000 (0xA130F9/0xA130FB, 1 MB window)
  V  movies         -> its page and the next mapped at 0x300000 (0xA130FD/0xA130FF, 1 MB window)
so an S item must not cross a page boundary and an M/V item must end within the page after its
first one. Items are packed tightly (biggest first, lowest free offset), so pages can mix windows.
Writes banks.s (one section per item plus <symbol>_page constants) and banks.ld (run address =
window + offset in the mapped pages, load address = ROM offset).
"""
import glob, os, sys

PAGE = 0x80000
WINDOWS = {'S': 0x180000, 'M': 0x200000, 'V': 0x300000}
SPAN = {'S': 1, 'M': 2, 'V': 2}           # pages visible through the window
CODE_END = 0xB8000                        # src/md.ld: ROM LENGTH (code + rodata + .data image)
ROM_MAX = 0x800000

def place(gaps, win, size):
    """Lowest offset in a free gap where an item of this window and size can sit."""
    for gi, (a, b) in enumerate(gaps):
        off = a
        while off + size <= b:
            if off + size <= (off // PAGE + SPAN[win]) * PAGE:
                return gi, off
            off = (off // PAGE + 1) * PAGE
    return None, None

def main():
    build = sys.argv[1]
    units = {}                      # (window, group or symbol) -> [(sym, path, size)]
    for fn in sorted(glob.glob(os.path.join(build, 'banked_*.txt'))):
        for line in open(fn):
            if line.strip():
                win, sym, path = line.split(None, 2)
                win, _, grp = win.partition(':')
                units.setdefault((win, grp or sym), []).append((sym, path.strip(), (os.path.getsize(path.strip()) + 1) & ~1))
    gaps = [(CODE_END, ROM_MAX)]
    placed = []                     # (offset, window, sym, path, size, page)
    for (win, name), members in sorted(units.items(), key=lambda u: (-sum(m[2] for m in u[1]), u[0][1])):
        size = sum(m[2] for m in members)
        gi, off = place(gaps, win, size)
        if gi is None:
            sys.exit(f'{name}: {size} bytes do not fit in {ROM_MAX // 1024} KB of ROM')
        a, b = gaps.pop(gi)
        gaps[gi:gi] = [g for g in ((a, off), (off + size, b)) if g[1] - g[0] >= 2]
        page = off // PAGE
        for sym, path, n in members:
            placed.append((off, win, sym, path, n, page))
            off += n
    placed.sort()
    s = ['| generated by tools/mkbanks.py -- do not edit']
    ld = ['/* generated by tools/mkbanks.py -- do not edit */']
    for off, win, sym, path, size, page in placed:
        sec = f'.bank_{sym}'
        s += [f'    .section {sec},"a"', f'    .globl {sym}', f'{sym}:', f'    .incbin "{os.path.abspath(path)}"',
              '    .balign 2', f'    .globl {sym}_page', f'    .set {sym}_page, {page}']
        ld.append(f'  {sec} 0x{WINDOWS[win] + off - page * PAGE:06X} : AT(0x{off:06X}) {{ KEEP(*({sec})) }}')
    end = max(o + n for o, _, _, _, n, _ in placed) if placed else CODE_END
    ld.append(f'_rom_end = 0x{end:06X};')
    open(os.path.join(build, 'banks.s'), 'w').write('\n'.join(s) + '\n')
    open(os.path.join(build, 'banks.ld'), 'w').write('\n'.join(ld) + '\n')
    for p in range(CODE_END // PAGE, (end + PAGE - 1) // PAGE):
        here = [(max(o, p * PAGE), min(o + n, (p + 1) * PAGE), w, sym) for o, w, sym, _, n, _ in placed
                if o < (p + 1) * PAGE and o + n > p * PAGE]
        used = sum(b - a for a, b, _, _ in here)
        print(f'page {p}: {used // 1024} KB: ' + ', '.join(f'{sym}({w})' for _, _, w, sym in here[:6])
              + (' ...' if len(here) > 6 else ''))
    print(f'ROM with banks: {end // 1024} KB')

main()
